from typing import Protocol

from app.domain.entities.client import Client


class ClientRepositoryPort(Protocol):
    async def get_all(self) -> list[Client]: ...

    async def get_by_id(self, client_id: int) -> Client | None: ...

    async def get_by_cpf_cnpj(self, cpf_cnpj: str) -> Client | None: ...

    async def add(self, client: Client) -> Client: ...

    async def update(self, client: Client) -> Client: ...

    async def is_referenced(self, client_id: int) -> bool:
        """Se há veículo ou ordem de serviço do cliente (o banco impede a exclusão)."""
        ...

    async def delete(self, client_id: int) -> None:
        """Exclui o cliente; levanta `ConflictError` se o banco recusar por vínculo."""
        ...
